def _merge_add():
    # v3.16：并入 ADD，按题干去重（原题优先）
    for _g, _mp in ADD.items():
        for _u in UNITS[_g]:
            if _u[0] not in _mp:
                continue
            _seen = set(t[0] for t in _u[1])
            for t in _mp[_u[0]]:
                assert len({str(t[1]), str(t[2][0]), str(t[2][1])}) == 3, t[0]
                if not (t[0] in _seen or _seen.add(t[0])):
                    _u[1].append(t)

_merge_add()

def main():
    import json, os
    out = []
    for grade, units in UNITS.items():
        for uname, qs in units:
            for q, a, wrongs, why in qs:
                out.append({
                    'q': q, 'a': str(a), 'options': [str(w) for w in wrongs],
                    'wrongReasons': [why, '再想想这个单元学过的课文'],
                    'grade': grade, 'level': 0, 'tag': '单元·' + uname.split(' ', 1)[1],
                    'unit': uname,
                    'speak': q.replace('？', '').replace('（　）', '').replace('《', '').replace('》', ''),
                    'id': 'cu%d-%02d' % (grade, len(out))
                })
    path = os.path.join(os.path.dirname(__file__), '..', 'data', 'banks', 'chinese-units.json')
    with open(path, 'w', encoding='utf-8') as f:
        json.dump(out, f, ensure_ascii=False, indent=1)
    print('生成', len(out), '道语文单元题')
    for g in sorted(UNITS):
        n = sum(len(qs) for u, qs in UNITS[g])
        print('  %d年级: %d 单元 / %d 题' % (g, len(UNITS[g]), n))

if __name__ == '__main__':
    main()
