def main():
    bank = json.load(open(PATH, encoding='utf-8'))
    bank = [q for q in bank if not str(q['id']).startswith('cx')]   # 幂等：清旧 cx
    # ① FIX 同音碰撞（g1/g4）
    fixed = 0
    for q in bank:
        key = (q['grade'], q['level'], q['a'])
        if key in FIX:
            q.update(FIX[key]); fixed += 1
    # ② 回填纪律字段（全库）
    for q in bank:
        q.setdefault('dif', q['level'])
        q.setdefault('tp', TP_BY_TAG.get(q['tag'], '词语'))
        q.setdefault('src', '通用语基')
    # ③ 追加 ADD
    added = 0
    for g, layers in ADD.items():
        for lv, rows in layers.items():
            for i, (q, a, wrongs, why, tp, tag) in enumerate(rows):
                bank.append({
                    'q': q, 'a': str(a), 'options': [str(w) for w in wrongs],
                    'wrongReasons': [why, '再读一遍题目，想想易错点在哪里'],
                    'grade': g, 'level': lv, 'dif': lv, 'tp': tp, 'tag': tag,
                    'src': '通用语基',
                    'speak': q.replace('（　）', '什么').replace('？', ''),
                    'id': 'cx%d-l%d-%d' % (g, lv, i)
                })
                added += 1
    # —— 自检（出题纪律）——
    for q in bank:
        opts = [str(o) for o in q['options']]
        assert str(q['a']) not in opts, '答案与干扰项冲突：%s' % q['id']
        assert len(set(opts)) == len(opts), '干扰项重复：%s' % q['id']
        assert len(opts) in (1, 2), '选项数异常：%s' % q['id']
        assert all(k in q for k in ('dif', 'tp', 'src')), '缺纪律字段：%s' % q['id']
    for g in (1, 4):
        for lv in range(1, 7):
            n = sum(1 for q in bank if q['grade'] == g and q['level'] == lv)
            assert n >= 20, 'g%d L%d 只有 %d 题（<20）' % (g, lv, n)
    with open(PATH, 'w', encoding='utf-8') as f:
        json.dump(bank, f, ensure_ascii=False, indent=1)
    print('字词全库 %d 题（修碰撞 %d，新增 %d）' % (len(bank), fixed, added))
    for g in (1, 4):
        cnt = [sum(1 for q in bank if q['grade'] == g and q['level'] == lv) for lv in range(1, 7)]
        judges = sum(1 for q in bank if q['grade'] == g and q['tp'] == '判断')
        print('  g%d 每层 %s，判断题 %d' % (g, cnt, judges))

