def _uniq(qs):
    seen, out = set(), []
    for t in qs:
        if t[0] not in seen:
            seen.add(t[0]); out.append(t)
    return out

def _pick2(cands, ans):
    ans = str(ans); ws = []
    for w in cands:
        w = str(w)
        if w != ans and w not in ws:
            ws.append(w)
    if len(ws) < 2:   # 候选不足时补两个明显不同的数
        n = int(ans) if ans.lstrip('-').isdigit() else 0
        for extra in (n + 3, n + 4, max(n - 3, 0)):
            w = str(extra)
            if w != ans and w not in ws:
                ws.append(w)
    return ws[:2]

