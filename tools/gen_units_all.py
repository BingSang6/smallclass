def main():
    out = []
    for grade, units in UNITS.items():
        for uname, qs in units:
            for q, a, wrongs, why in qs:
                out.append({
                    'q': q, 'a': a, 'options': wrongs,
                    'wrongReasons': [why, '把这个单元的知识点再想一想'],
                    'grade': grade, 'level': 0, 'tag': '单元·' + uname.split(' ', 1)[1],
                    'unit': uname, 'speak': q.replace('？', '').replace('○', '圆圈').replace('□', '方框'),
                    'id': 'ua%d-%02d' % (grade, len(out))
                })
    # 四上复用现有题库
    g4 = os.path.join(os.path.dirname(__file__), '..', 'data', 'banks', 'math-g4-units.json')
    with open(g4, encoding='utf-8') as f:
        old = json.load(f)
    for q in old:
        if not q.get('grade'):
            q['grade'] = 4
    out.extend(old)

    path = os.path.join(os.path.dirname(__file__), '..', 'data', 'banks', 'math-units.json')
    with open(path, 'w', encoding='utf-8') as f:
        json.dump(out, f, ensure_ascii=False, indent=1)
    print('生成', len(out), '道单元题 →', os.path.normpath(path))
    gs = {}
    for q in out:
        gs.setdefault(q['grade'], [0, set()])
        gs[q['grade']][0] += 1
        gs[q['grade']][1].add(q['unit'].split(' ')[0])
    for g in sorted(gs):
        print('  %d年级: %d 题 / %d 个单元' % (g, gs[g][0], len(gs[g][1])))

if __name__ == '__main__':
    main()
