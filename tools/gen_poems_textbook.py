    for grade, poems in POEMS.items():
        for pm in poems:
            others = [p for p in poems if p['t'] != pm['t']]
            u, t, au, dy, src = pm['u'], pm['t'], pm['au'], pm['dy'], pm['src']
            def wrong_for(text, which):
                cands = list(dict.fromkeys(
                    (y if which == 'b' else x)
                    for p in others for (x, y) in p['pairs']
                    if len(y if which == 'b' else x) == len(text)))
                for fb in FALLBACK.get(len(text), []):
                    if len(cands) >= 2: break
                    if fb != text and fb not in cands: cands.append(fb)
                assert len(cands) >= 2, '干扰句不足：%s' % text
                return cands[:2]
            for a, b in pm['pairs']:
                out.append(('《%s》接下句：%s，（　）' % (t, a), b, wrong_for(b, 'b'),
                            '背一背《%s》' % t, 1, 1, grade, u, t, src, '接句'))
                out.append(('《%s》接上句：（　），%s' % (t, b), a, wrong_for(a, 'a'),
                            '背一背《%s》' % t, 1, 1, grade, u, t, src, '接句'))
            if pm['pairs'] and others:  # 诗句识别
                wv = []
                for p in others:
                    if len(wv) >= 2: break
                    if p['pairs'][0][0] not in wv: wv.append(p['pairs'][0][0])
                out.append(('下列哪一句出自《%s》？' % t, pm['pairs'][0][0], wv[:2],
                            '想一想《%s》的原句' % t, 1, 1, grade, u, t, src, '识别'))
            if au:  # 作者（乐府/民歌/无名氏不出）
                wa = [p['au'] for p in others if p['au'] and p['au'] != au][:2]
                for fb in ('杜甫', '白居易', '李白'):
                    if len(wa) >= 2: break
                    if fb != au and fb not in wa: wa.append(fb)
                out.append(('《%s》的作者是谁？' % t, au, wa, '《%s》作者是%s' % (t, au), 2, 2, grade, u, t, src, '作者'))
            if au and dy and dy != '汉':  # 朝代（民歌跳过）
                wd = [d for d in ('唐', '宋', '元', '明', '清') if d != dy][:2]
                out.append(('《%s》的作者%s是哪个朝代的人？' % (t, au), dy, wd,
                            '%s是%s代人' % (au, dy), 2, 2, grade, u, t, src, '朝代'))
            for (q, a, ws, why) in pm['pin']:
                out.append((q, a, ws, why, 2, 2, grade, u, t, src, '字音'))
            for (q, a, ws, why) in pm['fill']:
                out.append((q, a, ws, why, 2, 2, grade, u, t, src, '生字'))
            for (q, a, ws, why) in pm['facts']:
                out.append((q, a, ws, why, 2, 2, grade, u, t, src, '常识'))
            for (q, a, ws, why) in pm['words']:
                out.append((q, a, ws, why, 3, 3, grade, u, t, src, '释义'))
            for (q, a, ws, why) in pm['judge']:
                out.append((q, a, ws, why, 3, 3, grade, u, t, src, '判断'))
            for (q, a, ws, why) in pm['moral']:
                out.append((q, a, ws, why, 4, 4, grade, u, t, src, '道理'))
            for (q, a, ws, why, dif) in pm['mq']:
                out.append((q, a, ws, why, dif, dif, grade, u, t, src, '接句'))
        for (q, a, ws, why) in CONTRAST[grade]:
            out.append((q, a, ws, why, 4, 5, grade, None, '综合', '课内综合', '对比'))
    return out

