def opts_of(opts_str, ans):
    parts = opts_str.replace("/", " ").split()
    return [p for p in parts if p != ans][:3]

def speak_clean(q):
    return q.replace("（　）", "什么").replace("（", "，").replace("）", "，")

def main():
    # 重新实现：按年级生成
    out = []
    BANDS = {1: [1, 2], 2: [3, 4], 3: [5, 6]}
    WRONGS_LV = WRONGS
    def add(g, q, a, options, level, tag, speak):
        options = [o for o in options if o and str(o) != str(a)]
        if len(options) < 2:   # 至少 2 个干扰项（答案+2=3 个按钮）
            return False
        out.append({"q": q, "a": a, "options": options[:3], "wrongReasons": WRONGS_LV[level],
                    "grade": g, "level": level, "tag": tag, "speak": speak})
        return True
    def sc(q):
        return q.replace("（　）", "什么").replace("（", "，").replace("）", "，")

    for band, grades in BANDS.items():
        for g in grades:
            # L1
            for (py, right, wrong, word) in L1[band]:
                ws = wrong.replace("/", " ").split()
                add(g, f"看拼音选字：{py}（　）", right, ws[:2], 1, "会认字", f"看拼音选字：{word}")
            # L2
            l2 = [t for t in L2[band] if isinstance(t, tuple)]
            for (sent, opts_str, ans) in l2:
                add(g, f"选字填空：{sent}", ans, opts_of(opts_str, ans), 2, "形近字", sc(sent))
            # L3
            for (word, ch, right, wrong) in L3[band]:
                if right is None or "_" in right: continue
                ws = [w for w in wrong.replace("/", " ").split() if w != right][:2]
                add(g, f"「{word}」的「{ch}」读什么？", right, ws, 3, "多音字", f"{word}的{ch}读什么")
            # L4
            for (sent, opts_str, ans) in L4[band]:
                add(g, f"选词填空：{sent}", ans, opts_of(opts_str, ans), 4, "词语搭配", sc(sent))
            # L5
            for (word, typ, right, wrong) in L5[band]:
                ws = [w for w in wrong.replace("/", " ").split() if w != right][:2]
                add(g, f"「{word}」的{typ}义词是？", right, ws, 5, f"{typ}义词", f"{word}的{typ}义词是")
            # L6
            for (sent, opts_str, ans) in L6[band]:
                add(g, sent, ans, opts_of(opts_str, ans), 6, "成语", sc(sent))

    # 去重 + id
    seen, final = set(), []
    for q in out:
        key = (q["grade"], q["q"])
        if key in seen: continue
        seen.add(key)
        q["id"] = f"c{q['grade']}-l{q['level']}-{len([x for x in final if x['grade']==q['grade'] and x['level']==q['level']])}"
        final.append(q)

    path = os.path.join(os.path.dirname(__file__), "..", "data", "banks", "chinese-words.json")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(final, f, ensure_ascii=False, indent=1)
    from collections import Counter
    print(f"OK: {len(final)} questions -> {os.path.normpath(path)}")
    print(sorted(Counter((q['grade'], q['level']) for q in final).items()))

if __name__ == "__main__":
    main()
