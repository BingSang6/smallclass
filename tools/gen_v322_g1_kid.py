def main():
    changed = 0
    for bank in ['math-units.json', 'chinese-units.json', 'english-units.json']:
        path = os.path.join(ROOT, bank)
        data = json.load(io.open(path, encoding='utf-8'))
        for q in data:
            if q.get('grade') != 1 or q['id'] not in M:
                continue
            nq, sp, ao = M[q['id']]
            if q['q'] != nq:
                changed += 1
            q['q'] = nq
            if sp:
                q['speak'] = sp
            if ao:
                q['a'], q['options'] = ao
            # ---- 纪律断言 ----
            assert len(nq) <= 18, (q['id'], nq)
            assert str(q['a']) not in [str(o) for o in q['options']], (q['id'], '答案混入干扰项')
            assert len({str(q['a']), *[str(o) for o in q['options']]}) == len(q['options']) + 1, (q['id'], '选项重复')
        # g1 全库纪律：题干短 + 答案唯一
        for q in data:
            if q.get('grade') == 1:
                assert len(q['q']) <= 18, ('g1 题干过长', q['id'], q['q'])
                assert str(q['a']) not in [str(o) for o in q['options']], (q['id'])
        io.open(path, 'w', encoding='utf-8', newline='').write(
            json.dumps(data, ensure_ascii=False, separators=(',', ':')) + '\n')
        print(bank, 'g1 rewritten ok')
    print('changed stems:', changed)


if __name__ == '__main__':
    main()
