# ---------- 生成 ----------
out = []
for unit, items in U.items():
    for i, (q, a, wrong, reason, tag) in enumerate(items):
        opts = list(dict.fromkeys(wrong))[:2]          # 去重保序，留 2 个
        while len(opts) < 2:                            # 补足干扰项
            alt = random.choice(['以上都不对', '无法确定'])
            if alt != a and alt not in opts: opts.append(alt)
        shuffled = opts[:]
        random.shuffle(shuffled)
        out.append({
            'q': q, 'a': a, 'options': shuffled,
            'wrongReasons': [reason, '再想想课本上的口诀'],
            'grade': 4, 'level': 0,                     # level 0：不进段位选题池
            'unit': unit, 'tag': '四上·' + tag,
            'id': 'u4-%d-%02d' % (list(U).index(unit) + 1, i + 1)
        })

# 去重校验
seen = set()
final = []
for x in out:
    if x['q'] in seen: continue
    seen.add(x['q']); final.append(x)

path = os.path.join(os.path.dirname(__file__), '..', 'data', 'banks', 'math-g4-units.json')
with open(path, 'w', encoding='utf-8') as f:
    json.dump(final, f, ensure_ascii=False, indent=1)
print('生成', len(final), '道单元题 →', os.path.normpath(path))
for u in U: print(' ', u, sum(1 for x in final if x['unit'] == u), '题')
